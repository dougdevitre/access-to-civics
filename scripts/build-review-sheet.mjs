#!/usr/bin/env node
/**
 * Generate the editorial review sheet — the document a human works through to sign off on the
 * plain-language layer.
 *
 * The README asks revisors, law librarians, bar association LRE committees, teachers and
 * students to check our work. Until now the only way to do that was to open JSON files and
 * cross-reference clause text by URN, which is not an ask anyone should make of a volunteer.
 *
 * One file per state, Markdown so it renders on GitHub where the collaborators are, generated
 * from the published corpus so it cannot drift from what ships. Each clause shows the verbatim
 * text with its source URL and checksum, both glosses, and the sensitivity call, followed by the
 * four questions a reviewer has to answer and a place to sign.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { isNamedReviewer, loadCorpora, loadSensitivity } from './lib/review.mjs';

const OUT_DIR = 'review';

/**
 * --check regenerates in memory and compares against what is committed, without writing.
 *
 * A stale review sheet is worse than no review sheet: a volunteer would read it carefully and
 * sign off on a gloss that is not the one shipping. So this runs in the gate set, and the fix
 * is always `npm run review:sheet`.
 */
const CHECK = process.argv.includes('--check');
let stale = 0;

function emit(file, contents) {
  if (!CHECK) {
    writeFileSync(file, contents);
    console.log(`[review-sheet] wrote ${file}`);
    return;
  }
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (current !== contents) {
    console.error(`[review-sheet] ${file} is ${current === null ? 'missing' : 'stale'} — run: npm run review:sheet`);
    stale++;
  }
}
const STATE_NAMES = {
  CA: 'California', DE: 'Delaware', FL: 'Florida', MO: 'Missouri',
  NE: 'Nebraska', NH: 'New Hampshire', TX: 'Texas', VA: 'Virginia',
};

const corpora = loadCorpora();
if (corpora.length === 0) {
  console.error('[review-sheet] no published corpus — run the ingest first');
  process.exit(1);
}
const sensitivity = loadSensitivity();

if (!CHECK) mkdirSync(OUT_DIR, { recursive: true });

const SENSITIVITY_MEANING = {
  none: 'renders normally to both age bands',
  historical_harm: 'never shown raw to ages 8–10; a teacher-mediated card appears instead',
  teacher_mediated: 'never shown raw to ages 8–10; a teacher-mediated card appears instead',
};

/** Markdown blockquote, so constitutional text is visually distinct from our prose. */
const quote = (text) => text.split('\n').map((line) => (line ? `> ${line}` : '>')).join('\n');

let indexRows = [];

for (const corpus of corpora) {
  const state = corpus.state;
  const name = STATE_NAMES[state] ?? state;
  const glossByUrn = new Map((corpus.glosses ?? []).map((g) => [g.clause_urn, g]));
  const clauses = [...(corpus.clauses ?? [])].sort((a, b) => a.urn.localeCompare(b.urn));
  const named = (corpus.glosses ?? []).filter((g) => isNamedReviewer(g.reviewed_by)).length;
  indexRows.push({ state, name, clauses: clauses.length, named, total: (corpus.glosses ?? []).length });

  const out = [];
  out.push(`# Editorial review — ${name}`);
  out.push('');
  out.push(
    `Generated by \`npm run review:sheet\` from \`data/published/${state.toLowerCase()}.json\`. ` +
      'Do not edit this file — it is regenerated. Record decisions as described at the bottom.',
  );
  out.push('');
  out.push(
    '**What needs checking, and what does not.** The clause text below is fetched from the ' +
      'official source and byte-verified against a stored checksum on every build, so it does not ' +
      'need your word for it — though if a citation points at the wrong provision, that is exactly ' +
      'the error we most want to hear about. What genuinely needs a human is the **plain-language ' +
      'gloss**, which is the sentence a child reads and believes, and the **sensitivity call**, ' +
      'which decides whether an eight-year-old sees a clause at all.',
  );
  out.push('');
  out.push(
    'A gloss can be accurate and still misleading — by leaving out the qualification that ' +
      'matters, or by making a contested reading sound settled. That is the harder failure and ' +
      'the one we most need help with.',
  );
  out.push('');
  out.push(`${clauses.length} ${clauses.length === 1 ? 'clause' : 'clauses'}.`);
  out.push('');

  for (const clause of clauses) {
    const gloss = glossByUrn.get(clause.urn);
    const review = sensitivity.clauses?.[clause.urn];
    const level = review?.sensitivity ?? 'unreviewed';
    const citation = `${name} Constitution, Article ${clause.article?.num}, Section ${clause.section}`;

    out.push('---');
    out.push('');
    out.push(`## ${citation}`);
    out.push('');
    if (clause.section_heading) out.push(`**Official heading:** ${clause.section_heading}`);
    out.push(`**URN:** \`${clause.urn}\``);
    out.push(`**Source fetched:** ${clause.source_url}`);
    if (clause.citation_url && clause.citation_url !== clause.source_url) {
      out.push(`**Page for a reader:** ${clause.citation_url}`);
    }
    out.push(`**Checksum of that document:** \`${clause.source_sha256}\``);
    if (clause.effective_date) out.push(`**Effective:** ${clause.effective_date}`);
    out.push('');
    out.push('### The clause, word for word');
    out.push('');
    out.push(quote(clause.text ?? '(no text)'));
    out.push('');
    out.push('### Plain language — ages 8–10');
    out.push('');
    out.push(gloss?.grade_5 ? quote(gloss.grade_5) : '> _(none)_');
    out.push('');
    out.push('### Plain language — ages 11–14');
    out.push('');
    out.push(gloss?.grade_8 ? quote(gloss.grade_8) : '> _(none)_');
    out.push('');
    out.push('### Sensitivity');
    out.push('');
    out.push(`\`${level}\` — ${SENSITIVITY_MEANING[level] ?? 'no review of record'}`);
    if (review?.teacher_note_8_10) {
      out.push('');
      out.push('Teacher-mediated card shown instead:');
      out.push('');
      out.push(quote(review.teacher_note_8_10));
    }
    out.push('');
    out.push('### Reviewer');
    out.push('');
    out.push('- [ ] The citation points at the provision we say it does');
    out.push('- [ ] The 8–10 gloss is a fair account of this clause');
    out.push('- [ ] The 11–14 gloss is a fair account of this clause');
    out.push('- [ ] Neither gloss leaves out a qualification that changes the meaning');
    out.push('- [ ] The sensitivity call is right for a child of that age');
    out.push('');
    out.push(
      `Current sign-off: **${gloss?.reviewed_by ?? '(none)'}**` +
        `${isNamedReviewer(gloss?.reviewed_by) ? '' : ' — a placeholder, not a person'}` +
        `${gloss?.reviewed_at ? `, ${gloss.reviewed_at}` : ''}`,
    );
    out.push('');
    out.push('Notes:');
    out.push('');
  }

  out.push('---');
  out.push('');
  out.push('## Recording a review');
  out.push('');
  out.push(
    'Sign-off lives in the seed data, not in this file. For each gloss you have checked, edit ' +
      `\`data/seed/${state.toLowerCase()}/glosses.json\` and set \`reviewed_by\` to your name or ` +
      'your committee\'s, and `reviewed_at` to the date. For the sensitivity calls, edit the ' +
      '`reviewed_by` and `reviewed_at` at the top of `data/seed/clause-sensitivity.json`.',
  );
  out.push('');
  out.push(
    'Then re-run `npm run ingest -- --state ' + state + ' --write` and `npm run review:status`. ' +
      'The app\'s grown-ups page reports the count, so a signed-off corpus says so in public and ' +
      'an unreviewed one says that too.',
  );
  out.push('');
  out.push(
    'If something is wrong, open an issue rather than editing the gloss in place — the ' +
      'disagreement is worth keeping. We will credit you unless you would rather we did not.',
  );
  out.push('');

  emit(`${OUT_DIR}/${state.toLowerCase()}.md`, out.join('\n'));
}

const index = [];
index.push('# Editorial review sheets');
index.push('');
index.push(
  'Generated by `npm run review:sheet`. One file per ingested state, pairing every clause\'s ' +
    'verbatim text with the plain-language glosses and the sensitivity call, so a reviewer can ' +
    'work through it without opening a JSON file.',
);
index.push('');
index.push(
  'The clause text is byte-verified on every build and needs nobody\'s word for it. The glosses ' +
    'and sensitivity calls are editorial judgement that no checksum can check. That is what these ' +
    'sheets are for.',
);
index.push('');
index.push('| State | Clauses | Glosses signed off by a named person |');
index.push('|---|---|---|');
for (const r of indexRows) {
  index.push(`| [${r.name}](${r.state.toLowerCase()}.md) | ${r.clauses} | ${r.named} of ${r.total} |`);
}
index.push('');
index.push('See `docs/09-editorial-review.md` for what a review involves and who we are asking.');
index.push('');
emit(`${OUT_DIR}/README.md`, index.join('\n'));

if (CHECK) {
  console.log(`[review-sheet] ${stale} sheet(s) out of date`);
  process.exit(stale > 0 ? 1 : 0);
}
